// Прямой запрос (1С++): строки приходных документов с распределением и дефектами.
//
// Что изменено по сравнению с исходным вариантом:
//  1. Убран LEFT JOIN _1SJOURN Журн1 — его поля нигде не использовались, соединение
//     только нагружало план (лишний поиск по журналу на каждую строку).
//  2. Дефектная ведомость агрегируется заранее в подзапросе (SUM по Приходная/Склад/
//     Товар/Серия/Цена) и ограничена только обрабатываемыми документами.
//     Раньше, если на один приход было несколько ведомостей или несколько строк
//     с одинаковым товаром/серией/ценой, строки прихода размножались.
//  3. Условие по виду документа перенесено в ON журнала, соединения записаны
//     в порядке «от временной таблицы», без обёрток-скобок вокруг полей.
|SELECT
|	Журн.IDDOC AS [ДокО $Документ.Приходная],
|	TRIM(Журн.DOCNO) AS НомерДокО,
|	$Док.Клиент AS [Клиент $Справочник.Клиенты],
|	$Док.Распределение AS Распределение,
|	ДокС.LINENO_ AS НомПр,
|	$ДокС.Товар AS [Товар $Справочник.Товары],
|	$ДокС.Серия AS [Серия $Справочник.Серии],
|	$ДокС.Цена AS Цена,
|	$Док.Склад AS [Склад $Справочник.Склады],
|	$ДокС.Количество AS ДокКоличество,
|	ISNULL($СпрР.Количество, 0) AS СпрКоличество,
|	$СпрР.Части AS СпрЧасти,
|	$СпрР.Пауза AS СпрПауза,
|	ISNULL($СпрР.НеОтдаватьСразу, 0) AS СпрНеОтдаватьСразу,
|	$СпрР.КоличествоНаПервуюПоставку AS СпрКоличествоНаПервуюПоставку,
|	ISNULL($СпрР.КоличествоДней, 0) AS СпрКоличествоДней,
|	СпрР.ID AS [СпрТекущийЭлемент $Справочник.Распределение],
|	$СпрР.Аптека AS [СпрАптека $Справочник.Клиенты],
|	$СпрР.НомерНакладнойПриходаКонтрагента AS СпрНомерНакладнойПриходаКонтрагента,
|	$ДокС.РЦ AS [РЦ $Справочник.Склады],
|	ISNULL(Деф.Количество, 0) AS КоличествоДефект,
|	ISNULL($APT.АптекаСклад, 1) AS СвободныйТовар
|FROM _1SJOURN Журн (NOLOCK)
|	INNER JOIN $Документ.Приходная Док (NOLOCK)
|		ON Док.IDDOC = Журн.IDDOC
|	INNER JOIN $ДокументСтроки.Приходная ДокС (NOLOCK)
|		ON ДокС.IDDOC = Журн.IDDOC
|	LEFT JOIN $Справочник.Распределение СпрР (NOLOCK)
|		ON $СпрР.КодРаспределения = $ДокС.КодРаспределения
|	LEFT JOIN $Справочник.Клиенты APT (NOLOCK)
|		ON APT.ID = $СпрР.Аптека
|	LEFT JOIN (
|		SELECT
|			$Дефект.Приходная AS Приходная,
|			$Дефект.Склад AS Склад,
|			$ДефектС.Товар AS Товар,
|			$ДефектС.Серия AS Серия,
|			$ДефектС.Цена AS Цена,
|			SUM($ДефектС.Количество) AS Количество
|		FROM $Документ.ДефектнаяВедомость Дефект (NOLOCK)
|			INNER JOIN $ДокументСтроки.ДефектнаяВедомость ДефектС (NOLOCK)
|				ON ДефектС.IDDOC = Дефект.IDDOC
|			-- Если нужно учитывать только проведённые и непомеченные ведомости
|			-- (видимо, для этого и был Журн1) — раскомментировать:
|			-- INNER JOIN _1SJOURN ЖурнД (NOLOCK)
|			--	ON ЖурнД.IDDOC = Дефект.IDDOC AND ЖурнД.CLOSED & 1 = 1 AND ЖурнД.ISMARK = 0
|		WHERE $Дефект.Приходная IN (SELECT Val FROM #ОбрабатываемыеДокументы)
|		GROUP BY
|			$Дефект.Приходная,
|			$Дефект.Склад,
|			$ДефектС.Товар,
|			$ДефектС.Серия,
|			$ДефектС.Цена
|	) Деф
|		ON  Деф.Приходная = Док.IDDOC
|		AND Деф.Склад  = $Док.Склад
|		AND Деф.Товар  = $ДокС.Товар
|		AND Деф.Серия  = $ДокС.Серия
|		AND Деф.Цена   = $ДокС.Цена
|WHERE Журн.IDDOCDEF = $ВидДокумента.Приходная
|	AND Журн.IDDOC IN (SELECT Val FROM #ОбрабатываемыеДокументы)
|ORDER BY ДокС.LINENO_
